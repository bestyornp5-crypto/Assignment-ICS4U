import java.util.Date;

public abstract class Book {
  // Global Variable
  private int bookId;
  private String title;
  private int numPages;
  private boolean isBorrowed;
  private String borrower;
  private Date dueDate;
  /* Provided code. Values for the book type (DO NOT DELETE) */
  public static final int HISTORY     = 0;   
  public static final int NON_FICTION = 1;  
  public static final int NOVEL       = 2;  
  
  
  //=============== Constructor =================
  /* Default constructor */
  public Book() {
    this.isBorrowed = false;
    this.borrower = null;
    this.dueDate = null;
  }
  
  /* The constructor that creates the book object 
   * @param bookId   - The book ID (Generated by the book counter) for the book
   * @param title    - The title of the book
   * @param numPages - Number of pages that book has */
  public Book(int bookId, String title, int numPages) {
    this.bookId = bookId;
    this.title = title;
    this.numPages = numPages;
    this.isBorrowed = false;
    this.borrower = null;
    this.dueDate = null;
  }
  
  //============= Private Methods ===============
  /* May add your own private methods here */   
  
  
  //============= Public Methods ================
  /* Checks if the book is borrowed or not
   * @return - true if the book is borrowed
   *           false if the book is still available */
  public boolean IsBorrowed() {

    return this.isBorrowed;   // Dummy return value
  }
  
  /* Gets the title of the book
   * @return - the title of the book */
  public String GetTitle() {
    return this.title;   // Dummy return value
  }
  
  /* Gets the number of pages the book has
   * @return - The number of pages the book has */ 
  public int GetNumPages() {
    return this.numPages;   // Dummy return value
  }
  
  /* Gets the book ID
   * @return - The book ID */   
  public int GetBookId() {
    return this.bookId;   // Dummy return value
  }
  
  /* Gets the name of the borrower 
   * @return - Returns the name of the borrower if someone did borrow
   *         - Returns null if no one borrowed it. */
  public String GetBorrower() {
    return this.borrower;   // Dummy return value
  }
  
  /* Sets the name of the borrower for this book
   * @param borrowerName - The name of the borrower */
  public void SetBorrower(String borrowerName) {
    if ( borrowerName != null && !borrowerName.isEmpty()){
      this.borrower = borrowerName;
      this.isBorrowed =  true;
    } else {
      this.isBorrowed = false;
    }
    
  }
  
  /* Specify that this book is returned back to the library */
  public void Return() {
    this.isBorrowed = false;
    this.borrower =  null;
    this.dueDate = null;
  }   
  
  /* Gets the due date for this book
   * @return - The Date object that contains the date that 
   *           the book is due */
  public Date GetDueDate() {
    return this.dueDate;   // Dummy return value
  }
  
  /* Sets the due date for this book
   * @param date - The Date object that contains the due date */
  public void SetDueDate(Date date) {
    this.dueDate = date;
    
  }
  
  /* Specify that the book is being borrowed
   * @param borrowerName - The borrower's name */
  public abstract boolean Borrow(String borrowerName, int numDays);
  
  /* Gets the extra info that is specific to the book type
   * and return to the caller in String format.
   * @return - The extra information */   
  public abstract String ExtraInfo();
}